// with-android-navbar.js — AN EXPO CONFIG PLUGIN: the Android navigation bar stops being a white slab under a dark app.
//
// The bar is drawn by the system, not by us, so no stylesheet reaches it. Two things decide what you see, and the
// generated project only ever had the first:
//
//   1. `android:navigationBarColor` — Expo's template already sets it to transparent.
//   2. `WindowCompat.setDecorFitsSystemWindows(window, false)` — without it the window STOPS at the bar, so the
//      transparent colour reveals the window background behind it, which is white. That call is what
//      `react-native-edge-to-edge` makes (`android.edgeToEdgeEnabled` in app.json), and it is the actual fix.
//
// This plugin adds the FALLBACK for when that is not in force: a bar painted the app's own background colour rather
// than the system's default. It costs nothing when edge-to-edge is on, because a transparent bar wins over it, and it
// is what stands between a white slab and the app if edge-to-edge is ever turned off or an OEM ignores it.
//
// The colour is per mode (`values` / `values-night`), and the icons drawn ON the bar are the reason it is not simply
// "the background of whichever theme":
//
//   - `windowLightNavigationBar` — dark icons on a pale bar — arrived in API 27, and this app's minSdk is 24.
//   - So below 27 a light bar would carry WHITE icons on WHITE, and be invisible. The default `values` colour is
//     therefore the DARK background, which is legible with the light icons those versions always draw; `values-v27`
//     is where the light theme gets its pale bar, with the flag that makes the icons dark.

const { withAndroidStyles, withDangerousMod, AndroidConfig } = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

/** The app's own canvas, from `src/theme.ts` — LIGHT.bg and DARK.bg. Keep them in step with it. */
const BG = { light: "#ffffff", dark: "#121316" };

/** One colors.xml, under whichever `values-…` directory it is written to, holding just the bar's colour. */
const colorsXml = (hex) => `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by plugins/with-android-navbar.js; do not edit -->
<resources>
  <color name="navigationBarFallback">${hex}</color>
</resources>
`;

/** One styles.xml, likewise, overriding the theme for an API level or a mode. */
const stylesXml = (items) => `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by plugins/with-android-navbar.js; do not edit -->
<resources>
  <style name="AppTheme" parent="Theme.AppCompat.DayNight.NoActionBar">
${items.map((i) => `    ${i}`).join("\n")}
  </style>
</resources>
`;

module.exports = function withAndroidNavbar(config) {
    // The base theme names the fallback rather than the system default. `windowDrawsSystemBarBackgrounds` has to stay
    // true or a colour on the bar — transparent or otherwise — is not applied at all.
    config = withAndroidStyles(config, (cfg) => {
        const theme = cfg.modResults.resources.style?.find((s) => s.$.name === "AppTheme");
        if (theme) {
            AndroidConfig.Styles.assignStylesValue(cfg.modResults, {
                add: true, parent: { name: "AppTheme", parent: "Theme.AppCompat.DayNight.NoActionBar" },
                name: "android:windowDrawsSystemBarBackgrounds", value: "true",
            });
        }
        return cfg;
    });

    return withDangerousMod(config, ["android", (cfg) => {
        const res = path.join(cfg.modRequest.platformProjectRoot, "app/src/main/res");
        const write = (dir, file, body) => {
            fs.mkdirSync(path.join(res, dir), { recursive: true });
            fs.writeFileSync(path.join(res, dir, file), body);
        };
        // Below API 27 the icons on the bar are always light, so the bar is the DARK canvas in both modes.
        write("values", "colors_navbar.xml", colorsXml(BG.dark));
        write("values-night", "colors_navbar.xml", colorsXml(BG.dark));
        // From 27 the light theme may have a pale bar, because the icons on it can be dark.
        write("values-v27", "colors_navbar.xml", colorsXml(BG.light));
        write("values-night-v27", "colors_navbar.xml", colorsXml(BG.dark));
        write("values-v27", "styles_navbar.xml", stylesXml([
            `<item name="android:navigationBarColor">@color/navigationBarFallback</item>`,
            `<item name="android:windowLightNavigationBar">true</item>`,
        ]));
        write("values-night-v27", "styles_navbar.xml", stylesXml([
            `<item name="android:navigationBarColor">@color/navigationBarFallback</item>`,
            `<item name="android:windowLightNavigationBar">false</item>`,
        ]));
        return cfg;
    }]);
};
