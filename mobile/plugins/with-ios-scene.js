// with-ios-scene.js — AN EXPO CONFIG PLUGIN: the iOS app adopts the UIScene lifecycle. iOS 27 terminates an app built
// against its SDK that does not (`_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`, a SIGTRAP at launch),
// and Expo 57's template still creates its window in `application(_:didFinishLaunchingWithOptions:)`. The native
// project is generated (`expo prebuild`) and not checked in, so the change is made here, on every prebuild:
//
//   - Info.plist declares one window scene, whose delegate is `SceneDelegate`;
//   - `SceneDelegate.swift` creates the window for its scene and starts React Native in it, with the factory the
//     app delegate already built;
//   - the app delegate stops creating a window of its own.
//
// Deep links (`application(_:open:)`) arrive at the scene now; the app has none yet. When it does, forward
// `scene(_:openURLContexts:)` to RCTLinkingManager in SceneDelegate.swift.

const { withAppDelegate, withDangerousMod, withInfoPlist, withXcodeProject, IOSConfig } = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const SCENE_DELEGATE = `// SceneDelegate.swift — generated by plugins/with-ios-scene.js: the app's one window scene. iOS 27 requires the scene
// lifecycle; the window React Native draws in is created here, with the factory AppDelegate built.
import UIKit
import React

class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {
    guard let windowScene = scene as? UIWindowScene,
          let app = UIApplication.shared.delegate as? AppDelegate,
          let factory = app.reactNativeFactory else { return }
    let window = UIWindow(windowScene: windowScene)
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: nil)
    self.window = window
    app.window = window
  }
}
`;

/** Info.plist: one window scene, delegated to SceneDelegate. */
const withSceneManifest = (config) => withInfoPlist(config, (c) => {
    c.modResults.UIApplicationSceneManifest = {
        UIApplicationSupportsMultipleScenes: false,
        UISceneConfigurations: {
            UIWindowSceneSessionRoleApplication: [{
                UISceneConfigurationName: "Default Configuration",
                UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
            }],
        },
    };
    return c;
});

/** AppDelegate.swift: build the factory as before, but leave the window to the scene. */
const withoutAppWindow = (config) => withAppDelegate(config, (c) => {
    const before = c.modResults.contents;
    const after = before.replace(/#if os\(iOS\) \|\| os\(tvOS\)\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*factory\.startReactNative\([^)]*\)\s*#endif/s,
        "// The window is the scene's (SceneDelegate.swift, plugins/with-ios-scene.js).");
    if (after === before && !before.includes("SceneDelegate.swift")) throw new Error("with-ios-scene: the AppDelegate template changed; its window block was not found");
    c.modResults.contents = after;
    return c;
});

/** SceneDelegate.swift: written beside AppDelegate.swift and compiled into the app target. */
const withSceneDelegateFile = (config) => {
    config = withDangerousMod(config, ["ios", async (c) => {
        const dir = path.join(c.modRequest.platformProjectRoot, c.modRequest.projectName);
        fs.writeFileSync(path.join(dir, "SceneDelegate.swift"), SCENE_DELEGATE);
        return c;
    }]);
    return withXcodeProject(config, (c) => {
        const name = c.modRequest.projectName;
        const file = `${name}/SceneDelegate.swift`;
        if (!c.modResults.hasFile(file)) {
            IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath: file, groupName: name, project: c.modResults });
        }
        return c;
    });
};

module.exports = (config) => withSceneDelegateFile(withoutAppWindow(withSceneManifest(config)));
