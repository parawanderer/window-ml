// pkg-pep440.ts — PEP 440 versions and version specifiers, read as Python's `packaging` 26.3 reads them, for the install verdict.

// The strings come from an index that is not trusted (docs/plan/repl/PACKAGES_INSTALL.md, "Trust"), so every parser
// here is total and bounded: an input longer than its cap, outside printable ASCII, or off the grammar is `null`,
// never an exception, and no regular expression is built from an input. Numbers stay decimal strings (an epoch or a
// release segment may have any number of digits), compared by length and then by digit. Where this is stricter than
// `packaging` it is on purpose and only for inputs no real release has: non-ASCII text, and the length caps.
// tests/pkg-pep.test.mjs holds the differential cases, generated by `packaging` itself.

/** The longest version string read; the longest in the pinned index snapshot is far shorter. */
export const MAX_VERSION_CHARS = 128;

/** The longest specifier set read (`requires_python`, or one requirement's ranges). */
export const MAX_SPECIFIER_CHARS = 1024;

/** A parsed PEP 440 version, normalized: numbers without leading zeros, a pre-release letter as `a`, `b` or `rc`. */
export interface Pep440Version {
    epoch: string;
    release: string[];
    pre: { letter: "a" | "b" | "rc"; n: string } | null;
    post: string | null;
    dev: string | null;
    local: string[] | null;
}

const VERSION_RE = /^\s*v?(?:([0-9]+)!)?([0-9]+(?:\.[0-9]+)*)(?:[-_.]?(alpha|a|beta|b|preview|pre|c|rc)[-_.]?([0-9]+)?)?(?:-([0-9]+)|[-_.]?(post|rev|r)[-_.]?([0-9]+)?)?(?:[-_.]?(dev)[-_.]?([0-9]+)?)?(?:\+([a-z0-9]+(?:[-_.][a-z0-9]+)*))?\s*$/i;
const ASCII_RE = /^[\t\n\v\f\r\x20-\x7e]*$/;

/** A decimal number without its leading zeros ("007" → "7", "000" → "0"). */
function num(s: string): string {
    const t = s.replace(/^0+/, "");
    return t === "" ? "0" : t;
}

/** Compare two normalized decimal strings. */
function cmpNum(a: string, b: string): number {
    if (a.length !== b.length) return a.length < b.length ? -1 : 1;
    return a < b ? -1 : a > b ? 1 : 0;
}

/** Parse a PEP 440 version, or `null` when it is not one. */
export function parseVersion(s: unknown): Pep440Version | null {
    if (typeof s !== "string" || s.length > MAX_VERSION_CHARS || !ASCII_RE.test(s)) return null;
    const m = VERSION_RE.exec(s);
    if (!m) return null;
    const preLetter = m[3]?.toLowerCase();
    return {
        epoch: num(m[1] ?? "0"),
        release: m[2].split(".").map(num),
        pre: preLetter === undefined ? null : {
            letter: preLetter === "alpha" || preLetter === "a" ? "a" : preLetter === "beta" || preLetter === "b" ? "b" : "rc",
            n: num(m[4] ?? "0"),
        },
        post: m[5] !== undefined ? num(m[5]) : m[6] !== undefined ? num(m[7] ?? "0") : null,
        dev: m[8] !== undefined ? num(m[9] ?? "0") : null,
        local: m[10] === undefined ? null : m[10].toLowerCase().split(/[-_.]/).map((x) => /^[0-9]+$/.test(x) ? num(x) : x),
    };
}

/** The version's release with its trailing zeros dropped: `1.0.0` and `1` are the same release. */
function trimmed(release: string[]): string[] {
    let n = release.length;
    while (n > 1 && release[n - 1] === "0") n--;
    return release.slice(0, n);
}

/** Compare two lists, element by element and then by length. */
function cmpList<T>(a: readonly T[], b: readonly T[], cmp: (x: T, y: T) => number): number {
    for (let i = 0; i < Math.min(a.length, b.length); i++) {
        const c = cmp(a[i], b[i]);
        if (c) return c;
    }
    return a.length === b.length ? 0 : a.length < b.length ? -1 : 1;
}

const PRE_RANK = { a: 0, b: 1, rc: 2 } as const;

/** Compare an optional number where absence is −∞ (`low`) or +∞. */
function cmpOpt(a: string | null, b: string | null, absent: "low" | "high"): number {
    if (a === null || b === null) {
        if (a === b) return 0;
        const aLow = absent === "low" ? a === null : a !== null;
        return aLow ? -1 : 1;
    }
    return cmpNum(a, b);
}

/** Order two versions as PEP 440 does (-1, 0 or 1): epoch, release, pre (a dev release of a final sorts first), post, dev, local. */
export function cmpVersion(a: Pep440Version, b: Pep440Version): number {
    let c = cmpNum(a.epoch, b.epoch);
    if (c) return c;
    c = cmpList(trimmed(a.release), trimmed(b.release), cmpNum);
    if (c) return c;
    // pre: a dev release with no pre and no post sorts before every pre-release; no pre at all sorts after them.
    const preKey = (v: Pep440Version): [number, number, string] =>
        v.pre ? [1, PRE_RANK[v.pre.letter], v.pre.n] : v.post === null && v.dev !== null ? [0, 0, "0"] : [2, 0, "0"];
    const pa = preKey(a), pb = preKey(b);
    c = Math.sign(pa[0] - pb[0] || pa[1] - pb[1]) || cmpNum(pa[2], pb[2]);
    if (c) return c;
    c = cmpOpt(a.post, b.post, "low");
    if (c) return c;
    c = cmpOpt(a.dev, b.dev, "high");
    if (c) return c;
    if (a.local === null || b.local === null) return a.local === b.local ? 0 : a.local === null ? -1 : 1;
    // A numeric local segment sorts after an alphanumeric one; numbers by value, the rest as strings.
    return cmpList(a.local, b.local, (x, y) => {
        const xn = /^[0-9]+$/.test(x), yn = /^[0-9]+$/.test(y);
        if (xn !== yn) return xn ? 1 : -1;
        return xn ? cmpNum(x, y) : x < y ? -1 : x > y ? 1 : 0;
    });
}

/** Whether a version is a pre-release (a pre or a dev segment). */
function isPre(v: Pep440Version): boolean {
    return v.pre !== null || v.dev !== null;
}

/** The version without its local label. */
function publicOf(v: Pep440Version): Pep440Version {
    return { ...v, local: null };
}

/** Epoch and release alone: the version every pre, post and dev release of it shares. */
function baseOf(v: Pep440Version): Pep440Version {
    return { epoch: v.epoch, release: v.release, pre: null, post: null, dev: null, local: null };
}

/** Same epoch and release, trailing zeros aside. */
function sameRelease(a: Pep440Version, b: Pep440Version): boolean {
    return cmpVersion(baseOf(a), baseOf(b)) === 0;
}

/** Same pre-release segment, or neither has one. */
function samePre(a: Pep440Version, b: Pep440Version): boolean {
    return a.pre === null ? b.pre === null : b.pre !== null && a.pre.letter === b.pre.letter && a.pre.n === b.pre.n;
}

/** One specifier: an operator and the version it compares with (`prefix` for `==1.2.*` and `!=1.2.*`). */
export type Pep440Specifier =
    | { op: "==="; raw: string }
    | { op: "==" | "!="; version: Pep440Version; prefix: boolean }
    | { op: "~=" | "<=" | ">=" | "<" | ">"; version: Pep440Version };

// The specifier grammar of `packaging` 26.3 (`Specifier._specifier_regex_str`), one alternative per operator family.
const PRE_SEG = "(?:[-_.]?(?:alpha|beta|preview|pre|a|b|c|rc)[-_.]?[0-9]*)?";
const POST_SEG = "(?:-[0-9]+|[-_.]?(?:post|rev|r)[-_.]?[0-9]*)?";
const DEV_SEG = "(?:[-_.]?dev[-_.]?[0-9]*)?";
const SPEC_BODY = "(?:===\\s*[^\\s;)]*"
    + "|(?:==|!=)\\s*v?(?:[0-9]+!)?[0-9]+(?:\\.[0-9]+)*(?:\\.\\*|" + PRE_SEG + POST_SEG + DEV_SEG + "(?:\\+[a-z0-9]+(?:[-_.][a-z0-9]+)*)?)?"
    + "|~=\\s*v?(?:[0-9]+!)?[0-9]+(?:\\.[0-9]+)+" + PRE_SEG + POST_SEG + DEV_SEG
    + "|(?:<=|>=|<|>)\\s*v?(?:[0-9]+!)?[0-9]+(?:\\.[0-9]+)*" + PRE_SEG + POST_SEG + DEV_SEG + ")";
const SPEC_RE = new RegExp("^\\s*" + SPEC_BODY + "\\s*$", "i");
/** The same grammar anchored at a position, for the requirement tokenizer (pkg-pep508.ts). */
export const SPEC_TOKEN_RE = new RegExp(SPEC_BODY, "iy");

/** Parse one specifier (`>=1.2`, `==1.*`, `===foo`), or `null` when it is not one. */
export function parseSpecifier(s: string): Pep440Specifier | null {
    if (s.length > MAX_SPECIFIER_CHARS || !ASCII_RE.test(s) || !SPEC_RE.test(s)) return null;
    const t = s.trim();
    const op = t.startsWith("===") ? "===" : /^(~=|==|!=|<=|>=)/.test(t) ? t.slice(0, 2) : t.slice(0, 1);
    const rest = t.slice(op.length).trim();
    if (op === "===") return { op, raw: rest };
    const prefix = rest.endsWith(".*");
    const version = parseVersion(prefix ? rest.slice(0, -2) : rest);
    if (!version) return null;
    if (op === "==" || op === "!=") return { op, version, prefix };
    return { op: op as "~=" | "<=" | ">=" | "<" | ">", version };
}

/** A comma-separated specifier set; the empty set admits every version. */
export type Pep440SpecifierSet = Pep440Specifier[];

/** Parse a specifier set (`>=3.9,<4`), or `null` when one of its parts is not a specifier. */
export function parseSpecifierSet(s: unknown): Pep440SpecifierSet | null {
    if (typeof s !== "string" || s.length > MAX_SPECIFIER_CHARS) return null;
    const out: Pep440SpecifierSet = [];
    for (const part of s.split(",")) {
        if (!part.trim()) continue;
        const spec = parseSpecifier(part);
        if (!spec) return null;
        out.push(spec);
    }
    return out;
}

/** `==V.*`: the version's epoch and release, padded with zeros, begin with V's. */
function prefixMatch(v: Pep440Version, spec: Pep440Version): boolean {
    if (v.epoch !== spec.epoch) return false;
    return spec.release.every((x, i) => (v.release[i] ?? "0") === x);
}

/** Whether one specifier admits a version (pre-releases admitted, as every call site here asks). */
function specAdmits(spec: Pep440Specifier, raw: string, v: Pep440Version | null): boolean {
    if (spec.op === "===") return raw.toLowerCase() === spec.raw.toLowerCase();
    if (!v) return false;
    const sv = spec.version;
    switch (spec.op) {
        case "==":
        case "!=": {
            const eq = spec.prefix ? prefixMatch(v, sv) : cmpVersion(sv.local ? v : publicOf(v), sv) === 0;
            return spec.op === "==" ? eq : !eq;
        }
        case "~=":
            return cmpVersion(publicOf(v), sv) >= 0
                && prefixMatch(v, { ...baseOf(sv), release: sv.release.slice(0, -1) });
        case "<=":
            return cmpVersion(publicOf(v), sv) <= 0;
        case ">=":
            return cmpVersion(publicOf(v), sv) >= 0;
        case "<":
            if (!(cmpVersion(v, sv) < 0)) return false;
            // `<V`, V not a pre-release, admits no pre-release OF V: one of V's release (and V's post, when V has one).
            return isPre(sv) || !isPre(v) || !sameRelease(v, sv) || (sv.post !== null && (v.pre !== null || v.post !== sv.post));
        case ">":
            if (!(cmpVersion(v, sv) > 0)) return false;
            // `>V` admits no local version of V, and, V neither a post nor a dev release, no post-release of V.
            if (cmpVersion(publicOf(v), sv) === 0) return false;
            return sv.post !== null || sv.dev !== null || v.post === null || !sameRelease(v, sv) || !samePre(v, sv);
    }
}

/** Whether every specifier of the set admits `version`, a string as the index gives it (an unparsable one is
 *  admitted only by a matching `===`, or by the empty set, which admits anything). Pre-releases are admitted: every call in the verdict passes
 *  `prereleases=True` or the default, which in `packaging` 26 admits a lone pre-release too. */
export function specifierSetContains(set: Pep440SpecifierSet, version: string): boolean {
    if (!set.length) return true;
    const v = parseVersion(version);
    if (!v && !set.some((s) => s.op === "===")) return false;
    return set.every((s) => specAdmits(s, version, v));
}

/** Whether two version strings are the same version (`1.0` and `1.0.0` are). */
export function sameVersion(a: string, b: string): boolean {
    const va = parseVersion(a), vb = parseVersion(b);
    return !!va && !!vb && cmpVersion(va, vb) === 0;
}
