// gen-pkg-core.mjs — write src/python/pkg-core.gen.ts, the measured stdlib surface of the pinned Pyodide core: which stdlib modules fail to import, which attributes the importable ones expose, and the platform it ran on.

// Read from notebooks/python-packages/data/platform-scan/core.json, which `node notebooks/python-packages/probe.mjs core`
// re-measures at each Pyodide pin bump. A missing, unparsable or empty input THROWS, never writes an empty table, and so does
// a scan of a different core than the one tools/pyodide-dist.json pins.
//
//   node scripts/gen-pkg-core.mjs           write the file
//   node scripts/gen-pkg-core.mjs --check   exit 1 when the file is not what this would write

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const IN = join(ROOT, "notebooks/python-packages/data/platform-scan/core.json");
const PIN = join(ROOT, "tools/pyodide-dist.json");
const OUT = join(ROOT, "src/python/pkg-core.gen.ts");

/** True for a plain object that holds at least one key. */
function filled(o) {
    return !!o && typeof o === "object" && !Array.isArray(o) && Object.keys(o).length > 0;
}

/**
 * The file's text, from the scan at `input`; throws, naming the file, when the scan cannot be trusted.
 * @param input path of core.json
 * @param pin path of the pin file whose artefact name source.core must equal, or null to skip the check
 */
function coreText(input, pin) {
    const fail = (why) => { throw new Error(`gen-pkg-core: ${input}: ${why}`); };
    if (!existsSync(input)) fail("missing; run node notebooks/python-packages/probe.mjs core");
    let scan;
    try { scan = JSON.parse(readFileSync(input, "utf8")); } catch (e) { fail(`not valid JSON (${e.message})`); }
    const row = scan && Array.isArray(scan.rows) ? scan.rows[0] : undefined;
    if (!row || typeof row !== "object") fail("has no rows[0]");
    if (!filled(row.bad)) fail("rows[0].bad is absent or empty");
    if (!filled(row.attrs)) fail("rows[0].attrs is absent or empty");
    const attrs = Object.fromEntries(Object.entries(row.attrs).filter(([, v]) => Array.isArray(v)));
    if (!filled(attrs)) fail("rows[0].attrs has only null entries");
    const src = scan.source || {};
    for (const k of ["core"]) if (typeof src[k] !== "string" || !src[k]) fail(`source.${k} is absent`);
    for (const k of ["commit", "extracted_at"]) if (typeof scan[k] !== "string" || !scan[k]) fail(`${k} is absent`);
    if (typeof row.machine !== "string" || typeof row.system !== "string" || !Array.isArray(row.version_info) || row.version_info.length < 3) fail("rows[0] lacks machine, system or version_info");
    if (pin) {
        const pinned = JSON.parse(readFileSync(pin, "utf8"))?.artefact?.name;
        if (src.core !== pinned) fail(`measured core ${src.core} is not the pinned core ${pinned} (${pin}); re-measure with node notebooks/python-packages/probe.mjs core`);
    }
    const sorted = Object.fromEntries(Object.keys(attrs).sort().map((k) => [k, attrs[k]]));
    const platform = { machine: row.machine, system: row.system, version: row.version_info.slice(0, 3) };
    const source = { core: src.core, commit: scan.commit, extractedAt: scan.extracted_at };
    return `// pkg-core.gen.ts — GENERATED by scripts/gen-pkg-core.mjs from notebooks/python-packages/data/platform-scan/core.json: what the pinned Pyodide core measurably lacks and exposes. Do not edit.

// \`node notebooks/python-packages/probe.mjs core\` re-measures it at each Pyodide pin bump.

/** The stdlib modules that fail to import on the core, sorted. */
export const PKG_CORE_MISSING: readonly string[] = ${JSON.stringify(Object.keys(row.bad).sort(), null, 4)};

/** The attributes each importable stdlib module exposes on the core, by module name. */
export const PKG_CORE_ATTRS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sorted, null, 4)};

/** The platform the core was measured on. */
export const PKG_CORE_PLATFORM: { machine: string; system: string; version: readonly [number, number, number] } = ${JSON.stringify(platform)} as { machine: string; system: string; version: readonly [number, number, number] };

/** Which core build was measured, at which commit of the probe, and when. */
export const PKG_CORE_SOURCE: { core: string; commit: string; extractedAt: string } = ${JSON.stringify(source, null, 4)};
`;
}

/**
 * Write src/python/pkg-core.gen.ts, leaving it untouched when it already says the same.
 * @param input path of core.json (tests pass a fixture); the pin check runs only for the default
 */
export function writePkgCore(input = IN, out = OUT) {
    const text = coreText(input, input === IN ? PIN : null);
    if (existsSync(out) && readFileSync(out, "utf8") === text) return;
    writeFileSync(out, text);
}

if (import.meta.url === `file://${process.argv[1]}`) {
    if (process.argv.includes("--check")) {
        if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== coreText(IN, PIN)) { console.error("src/python/pkg-core.gen.ts is stale: run node scripts/gen-pkg-core.mjs"); process.exit(1); }
    } else writePkgCore();
}
