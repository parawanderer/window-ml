// gen-core-env.mjs — write src/python/core-env.gen.ts, the pinned core's wheel tags, marker environment and Python, from the package oracle's env.json.

// python_install judges a PyPI wheel against the core it will run on (docs/plan/repl/PACKAGES_INSTALL.md, slice 3).
// Those facts come from the core itself: notebooks/python-packages/probe.mjs `env` asks the running core for its
// `packaging.tags.sys_tags()` and marker environment, and the notebook pins the answer in env.json for one core. This
// copies it into the bundle at build time (build.mjs, like build-info.gen.ts; the file is gitignored), so one pin bump's
// rerun of the notebook regenerates both (the pyodide-build skill, "After a bump"), and tests/pkg-index.test.mjs fails
// when it names another core than tools/pyodide-dist.json.
//
//   node scripts/gen-core-env.mjs           write the file
//   node scripts/gen-core-env.mjs --check   exit 1 when the file is not what this would write

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENV = join(ROOT, "notebooks/python-packages/data/pypi-compat/env.json");
const OUT = join(ROOT, "src/python/core-env.gen.ts");

/** The file's text, from env.json as it is now. */
function coreEnvText() {
    const env = JSON.parse(readFileSync(ENV, "utf8"));
    const row = env.rows[0];
    const facts = { core: env.source.core, python: row.python, tags: row.tags, markerEnv: row.env };
    return `// core-env.gen.ts — GENERATED by scripts/gen-core-env.mjs from the package oracle's env.json: the pinned core's wheel tags, marker environment and Python. Do not edit.

/** What the pinned core accepts and reports, as python_install's verdict judges a PyPI wheel against it. */
export const CORE_ENV: { core: string; python: string; tags: readonly string[]; markerEnv: Readonly<Record<string, string>> } = ${JSON.stringify(facts, null, 4)};
`;
}

/** Write src/python/core-env.gen.ts, leaving it untouched when it already says the same. */
export function writeCoreEnv() {
    const text = coreEnvText();
    if (existsSync(OUT) && readFileSync(OUT, "utf8") === text) return;
    writeFileSync(OUT, text);
}

if (import.meta.url === `file://${process.argv[1]}`) {
    if (process.argv.includes("--check")) {
        if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== coreEnvText()) { console.error("src/python/core-env.gen.ts is stale: run node scripts/gen-core-env.mjs"); process.exit(1); }
    } else writeCoreEnv();
}
