// Stamp the harness's own provenance into `build-info.gen.ts` (gitignored, like api-docs.gen.ts) so the
// `agent_api_docs` tool can tell the agent WHICH build it is: the public repo URL, the current commit +
// its date, and the build time. The extension can't run git at runtime, so this is captured at BUILD time.
// Run by build.mjs (and `npm run gen-build-info`) before bundling — tools.ts imports the generated const.
//
// Fails SOFT: a checkout without git (a tarball, a shallow CI clone with no history) just yields empty
// fields — the agent_api_docs section omits what it doesn't know rather than breaking the build.
import { writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "build-info.gen.ts");

/** Run a git command in the repo, returning trimmed stdout — or "" if git/history is unavailable. */
function git(args) {
    try { return execSync(`git ${args}`, { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); }
    catch { return ""; }
}

/** Normalize a git remote URL to a public HTTPS repo URL (scp-style/ssh → https, `.git` stripped).
 *  Pure — unit-tested. "" for a falsy input. */
export function normalizeRepoUrl(raw) {
    if (!raw) return "";
    return raw
        .replace(/^git@([^:]+):/, "https://$1/")   // scp-style: git@github.com:owner/repo → https://github.com/owner/repo
        .replace(/^ssh:\/\/git@/, "https://")       // ssh://git@github.com/owner/repo → https://…
        .replace(/\.git$/, "");
}

/** The public HTTPS repo URL from origin. "" if no remote. */
function repoUrl() {
    return normalizeRepoUrl(git("config --get remote.origin.url"));
}

/**
 * The changed file paths from `git status --porcelain` output. Porcelain v1 is `XY <path>` (rename:
 * `old -> new` — take the new). Strips the status code + whitespace with a REGEX, not a fixed slice(3),
 * because our `git()` helper `.trim()`s the whole output and eats the FIRST line's leading status space
 * (a real bug: `scripts/x` → `cripts/x`). Capped so a big WIP can't bloat the doc. Pure — unit-tested.
 * @param {string} status `git status --porcelain` output.
 * @returns {string[]} changed paths (the new path for renames), max 100.
 */
export function dirtyPathsFromStatus(status) {
    if (!status) return [];
    return status.split("\n")
        .map(l => l.replace(/^\s*\S+\s+/, "").split(" -> ").pop().replace(/^"|"$/g, ""))
        .filter(Boolean)
        .slice(0, 100);
}

/** Regenerate build-info.gen.ts in place. Called by build.mjs + npm scripts. */
export function writeBuildInfo() {
    const commit = git("rev-parse HEAD");
    const url = repoUrl();
    // Is the working tree DIRTY at build time — uncommitted changes (staged or unstaged) on top of `commit`?
    // `status --porcelain` prints one line per change, so any output = dirty. A build FROM a clean checkout is
    // exactly `commit`; a dev build usually isn't, and the export should say so (so a logged "91f98a1" is
    // trustworthy only when clean). Empty (no git) → false, same soft-fail as the rest.
    const status = git("status --porcelain");
    const dirty = status !== "";
    // The FILES that don't match `commit` in THIS build — so an agent reading the repo at that commit
    // (via agent_api_docs' source link) knows exactly which files won't match what's checked out here.
    const dirtyFiles = dirtyPathsFromStatus(status);
    // The EXACT diff of those changes — served by agent_api_docs ONLY on `{ diff: true }` (never by default),
    // so the agent can see precisely what differs from `commit` without a token cost on every call. Captured at
    // build time (the extension can't run git live). Capped so a big WIP can't bloat the bundle; empty when clean.
    const DIFF_CAP = 16000;
    const rawDiff = dirty ? git("diff HEAD") : "";
    const dirtyDiff = rawDiff.length > DIFF_CAP
        ? rawDiff.slice(0, DIFF_CAP) + `\n\n[diff truncated at ${DIFF_CAP} chars — ${dirtyFiles.length} file(s) changed; read them at the repo/commit for the rest]`
        : rawDiff;
    const info = {
        commit,
        shortCommit: git("rev-parse --short HEAD"),
        dirty,   // true = built with uncommitted changes on top of `commit` (not a reproducible build)
        dirtyFiles,   // which files those changes are in (empty when clean / no git)
        dirtyDiff,   // the exact `git diff HEAD` (capped) — served by agent_api_docs only on { diff: true }
        commitDate: git("show -s --format=%cI HEAD"),   // ISO-8601 committer date (when the commit was made)
        repoUrl: url,
        commitUrl: url && commit ? `${url}/commit/${commit}` : "",
        buildTime: new Date().toISOString(),
    };
    const module = "// GENERATED by scripts/gen-build-info.mjs — do not edit. Regenerated on every build.\n" +
        `export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;\n`;
    writeFileSync(OUT, module);
    return OUT;
}

if (process.argv[1] && process.argv[1].endsWith("gen-build-info.mjs")) {
    console.log(`generated ${writeBuildInfo()}`);
}
