// Stamp the harness's own provenance into `build-info.gen.ts` (gitignored, like api-docs.gen.ts) so the
// `agent_api_docs` tool can tell the agent WHICH build it is: the public repo URL, the current commit +
// its date, and the build time. The extension can't run git at runtime, so this is captured at BUILD time.
// Run by build.mjs (and `npm run gen-build-info`) before bundling — tools.ts imports the generated const.
//
// Fails SOFT: a checkout without git (a tarball, a shallow CI clone with no history) just yields empty
// fields — the agent_api_docs section omits what it doesn't know rather than breaking the build.
import { writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "build-info.gen.ts");

/** Run a git command in the repo, returning trimmed stdout — or "" if git/history is unavailable. */
function git(args) {
    try { return execSync(`git ${args}`, { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); }
    catch { return ""; }
}

/** Normalize a git remote URL to a public HTTPS repo URL (scp-style/ssh → https, `.git` stripped).
 *  Pure — unit-tested. "" for a falsy input. */
export function normalizeRepoUrl(raw) {
    if (!raw) return "";
    return raw
        .replace(/^git@([^:]+):/, "https://$1/")   // scp-style: git@github.com:owner/repo → https://github.com/owner/repo
        .replace(/^ssh:\/\/git@/, "https://")       // ssh://git@github.com/owner/repo → https://…
        .replace(/\.git$/, "");
}

/** The public HTTPS repo URL from origin. "" if no remote. */
function repoUrl() {
    return normalizeRepoUrl(git("config --get remote.origin.url"));
}

/** Regenerate build-info.gen.ts in place. Called by build.mjs + npm scripts. */
export function writeBuildInfo() {
    const commit = git("rev-parse HEAD");
    const url = repoUrl();
    const info = {
        commit,
        shortCommit: git("rev-parse --short HEAD"),
        commitDate: git("show -s --format=%cI HEAD"),   // ISO-8601 committer date (when the commit was made)
        repoUrl: url,
        commitUrl: url && commit ? `${url}/commit/${commit}` : "",
        buildTime: new Date().toISOString(),
    };
    const module = "// GENERATED by scripts/gen-build-info.mjs — do not edit. Regenerated on every build.\n" +
        `export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;\n`;
    writeFileSync(OUT, module);
    return OUT;
}

if (process.argv[1] && process.argv[1].endsWith("gen-build-info.mjs")) {
    console.log(`generated ${writeBuildInfo()}`);
}
