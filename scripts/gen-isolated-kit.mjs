// Bundle `src/isolated-kit.ts` into one source string, `src/isolated-kit.gen.ts` (gitignored, like api-docs.gen.ts), so
// the worker can splice the page's own pointer value into an isolated exec's wrapper (sw-isolated-exec.ts). A world
// built by `chrome.userScripts.execute` or CDP is handed source, never a module, so the class has to travel as text.
// Run by build.mjs before bundling. Rewritten only when it changes, so --watch does not trigger itself.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "isolated-kit.gen.ts");

/** The kit as an IIFE assigning `var __mlIsoKit`, minified. */
export function isolatedKitSource() {
    const r = esbuild.buildSync({
        entryPoints: [join(ROOT, "src", "isolated-kit.ts")], bundle: true, write: false, format: "iife", globalName: "__mlIsoKit",
        target: ["chrome114"], minify: true, legalComments: "none", logLevel: "silent",
    });
    return r.outputFiles[0].text.trim();
}

/** Write `src/isolated-kit.gen.ts` if its content changed. */
export function writeIsolatedKit() {
    const body = `// isolated-kit.gen.ts — GENERATED by scripts/gen-isolated-kit.mjs from src/isolated-kit.ts. Do not edit.\n\n/** The isolated exec's pointer value, as source that declares \`var __mlIsoKit\`. */\nexport const ISOLATED_KIT_SOURCE: string = ${JSON.stringify(isolatedKitSource())};\n`;
    if (existsSync(OUT) && readFileSync(OUT, "utf8") === body) return;
    writeFileSync(OUT, body);
}

if (import.meta.url === `file://${process.argv[1]}`) writeIsolatedKit();
