// gen-pkg-shipped.mjs — write src/python/pkg-shipped.gen.ts, the lock files the extension ships: the wheels build.mjs copies from pyodide-wheels/ into dist/pyodide.

// python_install's card counts a lock row as in the core only when its file is in this list, never from the lock alone:
// the lock names 354 packages and the extension ships its start-up set's closure (docs/plan/repl/PACKAGES_INSTALL.md,
// slice 4, ruled 2026-11-13). Read from pyodide-wheels/, the directory the build copies, so the list is what dist/pyodide
// holds; absent, nothing ships and every lock row is refused as `not-shipped`.
//
//   node scripts/gen-pkg-shipped.mjs           write the file
//   node scripts/gen-pkg-shipped.mjs --check   exit 1 when the file is not what this would write

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WHEELS = join(ROOT, "pyodide-wheels");
const OUT = join(ROOT, "src/python/pkg-shipped.gen.ts");

/** The file's text, from pyodide-wheels/ as it is now. */
function shippedText() {
    const files = existsSync(WHEELS) ? readdirSync(WHEELS).filter((f) => f.endsWith(".whl") || f.endsWith(".zip")).sort() : [];
    return `// pkg-shipped.gen.ts — GENERATED by scripts/gen-pkg-shipped.mjs from pyodide-wheels/: the lock files the extension ships in dist/pyodide. Do not edit.

/** The lock files the extension ships, by file name: a lock row is in the core only when its file is one of these. */
export const SHIPPED_LOCK_FILES: readonly string[] = ${JSON.stringify(files, null, 4)};
`;
}

/** Write src/python/pkg-shipped.gen.ts, leaving it untouched when it already says the same. */
export function writePkgShipped() {
    const text = shippedText();
    if (existsSync(OUT) && readFileSync(OUT, "utf8") === text) return;
    writeFileSync(OUT, text);
}

if (import.meta.url === `file://${process.argv[1]}`) {
    if (process.argv.includes("--check")) {
        if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== shippedText()) { console.error("src/python/pkg-shipped.gen.ts is stale: run node scripts/gen-pkg-shipped.mjs"); process.exit(1); }
    } else writePkgShipped();
}
